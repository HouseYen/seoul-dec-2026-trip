test('schema1 legacy restore preserves all ten values but not date; shopping roundtrip and invalid rejection', async ({page}) => {
  await page.goto('./#todos');
  const ids = await page.locator('.todo-check').evaluateAll(ns => ns.map(n => n.dataset.todoId));
  const todos = Object.fromEntries(ids.map((id,i) => [id,i%2===1]));
  const backup = {app:'seoul-dec-2026-trip',schemaVersion:1,todos,preferences:{date:'2026-12-03',base:'dongdaemun',snow:'ski'}};
  const upload = value => page.locator('#todo-import').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(value))});
  page.once('dialog', d => d.accept()); await upload(backup);
  await expect(page.locator('#app-status')).toContainText('已還原');
  await expect(page.locator('#date-option')).toHaveValue('2026-12-10');
  await expect(page.locator('#stay-area')).toHaveValue('dongdaemun');
  for (const [id,value] of Object.entries(todos)) await expect(page.locator(`[data-todo-id="${id}"]`)).toBeChecked({checked:value});
  await page.locator('#tab-map').click();
  await expect(page.locator('#shopping-plan')).toHaveValue('hongdae');
  await page.locator('#shopping-plan').selectOption('snow');
  await page.reload(); await expect(page.locator('#shopping-plan')).toHaveValue('snow');
  await page.locator('#tab-todos').click();
  const pending = page.waitForEvent('download'); await page.locator('#todo-export').click();
  const download = await pending; const exported = JSON.parse(await fs.readFile(await download.path(),'utf8'));
  expect(exported.preferences).toEqual({date:'2026-12-10',base:'dongdaemun',snow:'ski',shopping:'snow'});
  expect(exported.todos).toEqual(todos);
  for (const shopping of ['invalid',null,42]) {
    await upload({...backup,preferences:{...backup.preferences,shopping}});
    await expect(page.locator('#app-status')).toContainText('無法匯入');
    expect(await page.evaluate(() => JSON.parse(localStorage.getItem('seoul-trip-preferences-v2')).shopping)).toBe('snow');
  }
});
